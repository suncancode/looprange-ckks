"""heirrun.py -- compile one .mlir program with the REAL HEIR toolchain and run the REAL
Lattigo code that HEIR generates.  Nothing about the CKKS parameters is rebuilt by hand:
heir-opt chooses (or is told) first-mod-bits, heir-translate writes the Go code, and our
driver only calls the generated functions F__configure, F__encrypt__argI, F and
F__decrypt__result0.

    python3 heirrun.py prog.mlir --fmb 0|default|<bits> --inputs inputs.json --out DIR

inputs.json : a list of input sets; each set maps every secret argument name to a number
              (scalar f32 argument) or a list of S numbers (tensor<Sxf32> argument).
Prints one JSON line "RESULT {...}" with: the modulus chain actually used (bits of every
prime, logN, log2 QP), first-mod-bits passed, per input set the decrypted output, the exact
reference output, the max abs error and OK/WRONG, timings (configure = parameter + key
generation, encrypt, eval, decrypt) and the process's peak resident memory (VmHWM).

Correctness criterion (stated in the report):
    OK  iff  max_s |dec_s - ref_s| <= TOL * max(1, max_s |ref_s|),   TOL = 1e-3.
A wrap-around changes the result by a multiple of q/Delta >= 2, so every WRONG run is off
by >= 1 and every OK run in our data is off by < 1e-6; any TOL in [1e-6, 0.5] gives the
same classification (checked by the scripts: they also print the max error).
"""
from __future__ import annotations
import json, struct, os, re, subprocess, sys, time, shutil
from fractions import Fraction as F
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "looprange3"))
from mlir_reader import read
import concrete

TOL = 1e-3
SCALE = 45
GO = os.environ.get("GO", shutil.which("go") or "/usr/local/go/bin/go")
GOMOD = os.environ.get("W22_GOMOD", os.path.join(HERE, "..", "gomod"))
MIRRORS = os.environ.get("W22_GO_MIRRORS", "0") == "1"     # sandbox only: fetch x/ deps via GitHub
HEIR_BIN = os.environ.get("HEIR_BIN", "")                 # directory of heir-opt/heir-translate ("" = PATH)


def tool(name):
    return os.path.join(HEIR_BIN, name) if HEIR_BIN else name

GOMOD_TXT = """module w22

go 1.24

require github.com/tuneinsight/lattigo/v6 v6.2.0
"""
MIRROR_TXT = """
replace golang.org/x/exp => github.com/golang/exp v0.0.0-20250506013437-ce4c2cf36ca6
replace golang.org/x/crypto => github.com/golang/crypto v0.45.0
replace golang.org/x/sys => github.com/golang/sys v0.38.0
replace gopkg.in/yaml.v3 => github.com/go-yaml/yaml/v3 v3.0.1
replace gopkg.in/check.v1 => github.com/go-check/check v0.0.0-20161208181325-20d25e280405
"""


def go_env():
    env = dict(os.environ, GOFLAGS="-mod=mod")
    if MIRRORS:
        env.update(GOPROXY="direct", GOSUMDB="off")
    return env


def ensure_gomod():
    os.makedirs(GOMOD, exist_ok=True)
    gm = os.path.join(GOMOD, "go.mod")
    if not os.path.exists(gm):
        open(gm, "w").write(GOMOD_TXT + (MIRROR_TXT if MIRRORS else ""))


def sh(cmd, **kw):
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


DRIVER = r'''// Driver generated by heirrun.py.  It only calls functions that HEIR generated.
package main

import (
	"encoding/json"
	"fmt"
	"math"
	"os"
	"strings"
	"time"

	prog "w22/@PKG@"
)

func vmhwm() int {
	b, err := os.ReadFile("/proc/self/status")
	if err != nil { return -1 }
	for _, l := range strings.Split(string(b), "\n") {
		if strings.HasPrefix(l, "VmHWM:") {
			var kb int
			fmt.Sscanf(strings.TrimSpace(l[6:]), "%d", &kb)
			return kb
		}
	}
	return -1
}

func main() {
	raw, _ := os.ReadFile(os.Args[1])
	var sets []map[string]json.RawMessage
	if err := json.Unmarshal(raw, &sets); err != nil { panic(err) }
	t0 := time.Now()
	@CONFIGURE@
	tcfg := time.Since(t0).Seconds()
	q := []float64{}
	for _, v := range pa.Q() { q = append(q, math.Log2(float64(v))) }
	p := []float64{}
	for _, v := range pa.P() { p = append(p, math.Log2(float64(v))) }
	fmt.Printf("PARAMS {\"logN\": %d, \"Q_bits\": %s, \"P_bits\": %s, \"logQP\": %.2f, \"q0\": %d, \"configure_s\": %.4f}\n",
		pa.LogN(), js(q), js(p), pa.LogQP(), pa.Q()[0], tcfg)
	for i, s := range sets {
		_ = s
		te := time.Now()
@ENCRYPT@
		tenc := time.Since(te).Seconds()
		tv := time.Now()
		r := prog.F(@CALLARGS@)
		teval := time.Since(tv).Seconds()
		td := time.Now()
		out := prog.F__decrypt__result0(ev, pa, en, dec, r)
		tdec := time.Since(td).Seconds()
		fmt.Printf("OUT %d {\"out\": %s, \"level\": %d, \"encrypt_s\": %.4f, \"eval_s\": %.4f, \"decrypt_s\": %.4f}\n",
			i, js(out), @LEVEL@, tenc, teval, tdec)
	}
	fmt.Printf("MEM {\"vmhwm_kb\": %d}\n", vmhwm())
}

func js(v interface{}) string { b, _ := json.Marshal(v); return string(b) }
'''


def make_driver(gofile: str, pkg: str, argnames):
    src = open(gofile).read()
    enc_lines, call = [], ["ev, pa, en"]
    for i, name in enumerate(argnames):
        m = re.search(rf"func F__encrypt__arg{i}\([^)]*v0 (\[\]float32|float32)\)", src)
        if not m: raise RuntimeError(f"cannot find F__encrypt__arg{i} in generated code")
        if m.group(1) == "float32":
            enc_lines.append(f'\t\tvar a{i} float64\n\t\tjson.Unmarshal(s["{name}"], &a{i})\n'
                             f'\t\tc{i} := prog.F__encrypt__arg{i}(ev, pa, en, enc, float32(a{i}))')
        else:
            enc_lines.append(f'\t\tvar a{i} []float64\n\t\tjson.Unmarshal(s["{name}"], &a{i})\n'
                             f'\t\tb{i} := make([]float32, len(a{i}))\n\t\tfor j := range a{i} {{ b{i}[j] = float32(a{i}[j]) }}\n'
                             f'\t\tc{i} := prog.F__encrypt__arg{i}(ev, pa, en, enc, b{i})')
        call.append(f"c{i}")
    bts = re.search(r"func F__configure\(\) \(\*bootstrapping\.Evaluator", src) is not None
    if bts:
        call = ["bts"] + call
    configure = ("bts, ev, pa, en, enc, dec := prog.F__configure()" if bts
                 else "ev, pa, en, enc, dec := prog.F__configure()")
    ret_multi = re.search(r"func F\(.*?\) \(\[\]\*rlwe\.Ciphertext\)", src) is not None
    level = "r[0].Level()" if ret_multi else "r.Level()"
    d = DRIVER.replace("@CONFIGURE@", configure).replace("@PKG@", f"pkgs/{pkg}").replace("@ENCRYPT@", "\n".join(enc_lines)) \
              .replace("@CALLARGS@", ", ".join(call)).replace("@LEVEL@", level)
    return d


def f32_round(inputs):
    """Round every input value to the nearest float32 (as float64).  HEIR's encryption functions
    take float32, so the driver encrypts float32(x); rounding here makes the exact reference
    (concrete.run) use exactly the same input values as the encrypted run (fix of 26/10/2026)."""
    r = lambda x: struct.unpack("f", struct.pack("f", float(x)))[0]
    return [{k: ([r(x) for x in v] if isinstance(v, list) else r(v)) for k, v in s.items()} for s in inputs]


def compile_and_run(mlir: str, fmb, inputs, outdir: str, pkg: str, keep_ir: bool = True, timeout=3600):
    """fmb: 0 (HEIR's own range analysis), 'default' (no option: 55 bits), or an int."""
    ensure_gomod()
    inputs = f32_round(inputs)
    os.makedirs(outdir, exist_ok=True)
    prog = read(mlir)
    argnames = [o.dst for o in prog.inputs()]
    opts = f"scaling-mod-bits={SCALE}" + ("" if fmb == "default" else f" first-mod-bits={fmb}")
    res = dict(program=os.path.basename(mlir), fmb=fmb, outdir=outdir)
    t0 = time.time()
    r = sh([tool("heir-opt"), "--annotate-module=backend=lattigo scheme=ckks", f"--mlir-to-ckks={opts}",
            "--scheme-to-lattigo", mlir], timeout=timeout)
    res["heir_opt_s"] = round(time.time() - t0, 3)
    open(os.path.join(outdir, "heir_messages.txt"), "w").write(r.stderr)
    if r.returncode != 0:
        res["status"] = "REFUSED"; res["message"] = r.stderr.strip().splitlines()[-1:] ; return res
    open(os.path.join(outdir, "prog_lattigo.mlir"), "w").write(r.stdout)
    if keep_ir:
        r2 = sh([tool("heir-opt"), "--annotate-module=backend=lattigo scheme=ckks", f"--mlir-to-ckks={opts}",
                 "--mlir-print-ir-before=generate-param-ckks", mlir], timeout=timeout)
        open(os.path.join(outdir, "ir_before_param.txt"), "w").write(r2.stderr)
    pdir = os.path.join(GOMOD, "pkgs", pkg); os.makedirs(pdir, exist_ok=True)
    r = sh([tool("heir-translate"), "--emit-lattigo", f"--package-name={pkg}", os.path.join(outdir, "prog_lattigo.mlir")])
    if r.returncode != 0:
        res["status"] = "TRANSLATE-FAIL"; res["message"] = r.stderr[-400:]; return res
    gosrc = r.stdout
    gofile = os.path.join(pdir, "prog.go"); open(gofile, "w").write(gosrc)
    shutil.copy(gofile, os.path.join(outdir, "prog.go.txt"))
    cdir = os.path.join(GOMOD, "cmd", pkg); os.makedirs(cdir, exist_ok=True)
    open(os.path.join(cdir, "main.go"), "w").write(make_driver(gofile, pkg, argnames))
    shutil.copy(os.path.join(cdir, "main.go"), os.path.join(outdir, "main.go.txt"))
    binp = os.path.join(outdir, "prog.bin")
    t0 = time.time()
    r = sh([GO, "build", "-o", binp, f"./cmd/{pkg}"], cwd=GOMOD, env=go_env(), timeout=timeout)
    res["go_build_s"] = round(time.time() - t0, 2)
    if r.returncode != 0:
        open(os.path.join(outdir, "build_messages.txt"), "w").write(r.stderr)
        res["status"] = "BUILD-FAIL"; res["message"] = r.stderr[-600:]; return res
    inf = os.path.join(outdir, "inputs.json"); json.dump(inputs, open(inf, "w"))
    r = sh([binp, inf], timeout=timeout)
    open(os.path.join(outdir, "run.txt"), "w").write(r.stdout + r.stderr)
    if r.returncode != 0:
        res["status"] = "RUN-FAIL"; res["message"] = (r.stdout + r.stderr)[-600:]; return res
    params, outs, mem = None, {}, None
    for line in r.stdout.splitlines():
        if line.startswith("PARAMS "): params = json.loads(line[7:])
        elif line.startswith("OUT "):
            i, js = line[4:].split(" ", 1); outs[int(i)] = json.loads(js)
        elif line.startswith("MEM "): mem = json.loads(line[4:])
    res.update(params=params, mem_kb=mem["vmhwm_kb"] if mem else None)
    sets, worst, wrong = [], 0.0, 0
    for i, inp in enumerate(inputs):
        ref, _ = concrete.run(prog, {k: (v if isinstance(v, list) else [v]) for k, v in inp.items()})
        ref = [float(x) for x in ref[0]]
        got = outs[i]["out"]; got = got if isinstance(got, list) else [got]
        n = min(len(ref), len(got)) if len(ref) > 1 else 1
        err = max(abs(got[s] - ref[s if len(ref) > 1 else 0]) for s in range(n))
        scale = max(1.0, max(abs(x) for x in ref))
        ok = err <= TOL * scale
        wrong += (not ok); worst = max(worst, err)
        sets.append(dict(err=err, ok=ok, ref_max=max(abs(x) for x in ref),
                         eval_s=outs[i]["eval_s"], level=outs[i]["level"]))
    res.update(sets=sets, wrong=wrong, total=len(inputs), max_err=worst,
               status="OK" if wrong == 0 else f"WRONG({wrong}/{len(inputs)})",
               eval_s=sum(s["eval_s"] for s in sets) / len(sets),
               configure_s=params["configure_s"] if params else None)
    os.remove(binp)
    return res


if __name__ == "__main__":
    a = sys.argv[1:]
    mlir = a[0]
    fmb = a[a.index("--fmb") + 1]
    fmb = fmb if fmb == "default" else int(fmb)
    inputs = json.load(open(a[a.index("--inputs") + 1]))
    out = a[a.index("--out") + 1]
    pkg = re.sub(r"[^A-Za-z0-9_]", "_", os.path.basename(out.rstrip("/")))
    print("RESULT " + json.dumps(compile_and_run(mlir, fmb, inputs, out, pkg)))
